// Rebuild/check the portable skill from the same geometry and renderer as the site.
import { readFile, writeFile, mkdir, mkdtemp, rm } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { tmpdir } from 'node:os';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import ts from 'typescript';
import sharp from 'sharp';

const root = fileURLToPath(new URL('../', import.meta.url));
const kit = join(root, 'skills/atomsai-illustrations');
const check = process.argv.includes('--check');
const temp = await mkdtemp(join(tmpdir(), 'atomsai-skill-kit-'));
const hash = value => createHash('sha256').update(value).digest('hex');
const inputs = {};
const outputs = new Map();
async function source(path) { const text = await readFile(join(root, path), 'utf8'); inputs[path] = hash(text); return text; }
const emit = (file, content) => outputs.set(file, Buffer.from(content));
try {
  const metrics = await source('src/scripts/illustration-3d/data/reference-metrics.json');
  const page = await source('src/pages/illustration.astro');
  const gallery = [...page.matchAll(/\{ slug: '([^']+)', title:/g)].map(match => match[1]);
  for (const name of ['colors', 'geometry', 'primitives', 'models', 'render']) {
    let text = await source(name === 'colors' ? 'src/data/colors.ts' : `src/scripts/illustration-3d/${name}.ts`);
    text = text.replace("import metrics from './data/reference-metrics.json';", `const metrics = ${metrics};`);
    // Expose the unchanged gallery fitting function for new, unregistered recipes.
    if (name === 'models') text += '\nexport { fit as fitToReference };\n';
    const code = '// Generated by scripts/build-illustration-skill.mjs. Do not edit.\n' + ts.transpileModule(text, {
      compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 },
    }).outputText.replace(/from '\.\/(geometry|primitives)'/g, "from './$1.mjs'").replace("from '../../data/colors'", "from './colors.mjs'");
    emit(`runtime/${name}.mjs`, code);
    await writeFile(join(temp, `${name}.mjs`), code);
  }
  const { makeScene } = await import(pathToFileURL(join(temp, 'models.mjs')));
  const { renderScene } = await import(pathToFileURL(join(temp, 'render.mjs')));
  const { colors } = await import(pathToFileURL(join(temp, 'colors.mjs')));
  const references = ['layers', 'modular', 'orbit', 'always-on', 'filtering', 'versatility'];
  assert(references.every(slug => gallery.includes(slug)), 'A skill reference is no longer in the gallery');
  const labels = ['Layers', 'Modular', 'Orbit', 'Always on', 'Filtering', 'Versatility'];
  for (const [name, white, yaw, pitch] of [['neutral-dark', false, 0, 0], ['neutral-light', true, 0, 0], ['rotated-dark', false, .65, -.35]]) {
    const composites = [];
    for (let i = 0; i < references.length; i++) {
      const svg = renderScene(makeScene(references[i]), { white, yaw, pitch });
      const bg = white ? colors.paper.hex : colors.forestShade.hex, ink = white ? colors.forestShade.hex : colors.paper.hex;
      const figure = await sharp(Buffer.from(svg)).resize(300, 300).flatten({ background: bg }).png().toBuffer();
      composites.push({ input: figure, left: i % 3 * 320 + 10, top: Math.floor(i / 3) * 340 });
      const label = Buffer.from(`<svg width="320" height="40"><text x="160" y="24" fill="${ink}" font-family="sans-serif" font-size="14" text-anchor="middle">${labels[i]}</text></svg>`);
      composites.push({ input: label, left: i % 3 * 320, top: Math.floor(i / 3) * 340 + 300 });
    }
    emit(`assets/${name}.png`, await sharp({ create: { width: 960, height: 680, channels: 4, background: white ? colors.paper.hex : colors.forestShade.hex } }).composite(composites).png().toBuffer());
  }
  emit('assets/reference-manifest.json', JSON.stringify({
    version: 2, source: 'Current local gallery renderer; historical SVG masters are not visual baselines.',
    gallery, references, inputs, runtime: Object.fromEntries([...outputs].filter(([file]) => file.startsWith('runtime/')).map(([file, bytes]) => [file, hash(bytes)])),
    palette: { iris: colors.iris.hex, dark: colors.forestShade.hex, light: colors.paper.hex },
    projection: { size: 384, yawDegrees: 45, pitchDegrees: 30, stroke: 1.28, hiddenOpacity: .35 },
  }, null, 2) + '\n');
  for (const [file, bytes] of outputs) {
    const target = resolve(kit, file);
    if (check) assert.deepEqual(await readFile(target), bytes, `Stale illustration kit: ${file}. Run node scripts/build-illustration-skill.mjs`);
    else { await mkdir(resolve(target, '..'), { recursive: true }); await writeFile(target, bytes); }
  }
  console.log(`${check ? 'Verified' : 'Generated'} portable renderer and 3 visual reference sheets from ${gallery.length} current gallery examples.`);
} finally { await rm(temp, { recursive: true, force: true }); }
